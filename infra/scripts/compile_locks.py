"""Compile the inference service's hashed dependency locks (arch §7.2).

Reads services/inference/requirements/service.in (owned by Dev A) and writes one
lock per platform with `uv pip compile`, so every lock can be produced from any
machine:

    linux-x86_64-cpu      Docker and Linux CI         (torch from the PyTorch CPU index)
    windows-x86_64-cpu    Windows CI / no-GPU devs    (torch from the PyTorch CPU index)
    windows-x86_64-cu130  GPU development machine     (torch from the PyTorch cu130 index)

The PyTorch index is added with --extra-index-url (not --index-url) so PyPI stays
available for every other package. Cognee locks are out of scope: core and optional
locks never mix.

Usage:
    python infra/scripts/compile_locks.py             # write locks
    python infra/scripts/compile_locks.py --check     # lock-drift check: recompile, fail on any diff
    python infra/scripts/compile_locks.py --dry-run   # print the uv commands only
    python infra/scripts/compile_locks.py --platform linux-x86_64-cpu

Exit status 0 on success, 1 on drift or a failed compile. A missing service.in or
a missing `uv` stops with an error message (SystemExit). The script never invents a
lock. Standard library only; `uv` must be on PATH (this script does not install it).
"""
from __future__ import annotations

import argparse
import difflib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PYTHON_VERSION = "3.10.11"
TORCH_INDEX = "https://download.pytorch.org/whl"
REQ_DIR = Path("services/inference/requirements")
INPUT_NAME = "service.in"

# name -> (uv --python-platform, PyTorch index suffix)
PLATFORMS: dict[str, tuple[str, str]] = {
    "linux-x86_64-cpu": ("x86_64-manylinux_2_28", "cpu"),
    "windows-x86_64-cpu": ("windows", "cpu"),
    "windows-x86_64-cu130": ("windows", "cu130"),
}


class LockError(Exception):
    pass


def build_command(name: str, output: Path) -> list[str]:
    """The `uv pip compile` argv for one platform (run with cwd = repository root)."""
    platform, index = PLATFORMS[name]
    return [
        "uv", "pip", "compile", (REQ_DIR / INPUT_NAME).as_posix(),
        "--python-version", PYTHON_VERSION,
        "--python-platform", platform,
        "--generate-hashes",
        "--extra-index-url", f"{TORCH_INDEX}/{index}",
        "--index-strategy", "unsafe-best-match",
        "--no-header",
        "--output-file", str(output),
    ]


def header(name: str) -> str:
    platform, index = PLATFORMS[name]
    return (
        f"# Generated by infra/scripts/compile_locks.py from {REQ_DIR.as_posix()}/{INPUT_NAME}. Do not edit.\n"
        f"# Python {PYTHON_VERSION}, uv --python-platform {platform}, --generate-hashes.\n"
        f"# PyTorch index (--extra-index-url): {TORCH_INDEX}/{index}\n"
        f"# Install: pip install --require-hashes --no-deps -r {REQ_DIR.as_posix()}/{name}.txt\n"
    )


def compile_one(root: Path, name: str, output: Path) -> None:
    proc = subprocess.run(build_command(name, output), cwd=root, capture_output=True, text=True)
    if proc.returncode != 0:
        raise LockError(f"uv failed for {name} (exit {proc.returncode}):\n{proc.stderr.strip()}")
    body = output.read_text(encoding="utf-8").replace("\r\n", "\n")
    with open(output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header(name) + body)


def check_environment(root: Path, need_uv: bool) -> None:
    if not (root / REQ_DIR / INPUT_NAME).is_file():
        raise SystemExit(
            f"error: {REQ_DIR / INPUT_NAME} not found under {root}. The inference dependency inputs "
            "(Dev A) must be merged first; no lock is generated without them."
        )
    if need_uv and shutil.which("uv") is None:
        raise SystemExit("error: `uv` not found on PATH (https://docs.astral.sh/uv/). Install it, or use --dry-run.")


def run(root: Path, names: list[str], check: bool) -> int:
    drift = 0
    with tempfile.TemporaryDirectory() as tmp:
        for name in names:
            target = root / REQ_DIR / f"{name}.txt"
            out = Path(tmp) / f"{name}.txt" if check else target
            out.parent.mkdir(parents=True, exist_ok=True)
            try:
                compile_one(root, name, out)
            except LockError as exc:
                print(f"FAIL {name}: {exc}", file=sys.stderr)
                return 1
            if not check:
                print(f"wrote {target.relative_to(root).as_posix()}")
                continue
            rel = target.relative_to(root).as_posix()
            if not target.is_file():
                print(f"DRIFT {name}: {rel} is missing")
                drift += 1
                continue
            old = target.read_text(encoding="utf-8").replace("\r\n", "\n").splitlines(keepends=True)
            new = out.read_text(encoding="utf-8").splitlines(keepends=True)
            if old != new:
                drift += 1
                print(f"DRIFT {name}: {rel} differs from a fresh compile")
                sys.stdout.writelines(difflib.unified_diff(old, new, "committed", "recompiled", n=1))
            else:
                print(f"ok    {name}")
    return 1 if drift else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Compile hashed inference locks with uv (arch §7.2).")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2], help="repository root")
    ap.add_argument("--platform", choices=sorted(PLATFORMS), action="append", help="limit to one or more locks")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="recompile to a temp dir and fail on any diff")
    mode.add_argument("--dry-run", action="store_true", help="print the uv commands, run nothing")
    args = ap.parse_args(argv)

    root = args.root.resolve()
    names = args.platform or sorted(PLATFORMS)
    check_environment(root, need_uv=not args.dry_run)
    if args.dry_run:
        for name in names:
            print(" ".join(build_command(name, REQ_DIR / f"{name}.txt")))
        return 0
    return run(root, names, args.check)


if __name__ == "__main__":
    sys.exit(main())
