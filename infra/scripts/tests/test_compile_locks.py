"""Tests for infra/scripts/compile_locks.py (offline: no uv, no network)."""
import sys
from pathlib import Path

import pytest

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))

import compile_locks  # noqa: E402

TARGET = compile_locks.TARGETS["linux-x86_64-cpu"]
H = "--hash=sha256:" + "a" * 64
FIND_LINKS = "https://download.pytorch.org/whl/cpu/torch/"

GOOD = f"""# This file was autogenerated by uv via the following command:
#    python infra/scripts/compile_locks.py --target linux-x86_64-cpu
--index-url https://pypi.org/simple
--find-links {FIND_LINKS}

numpy==2.2.6 \\
    {H}
    # via pandas
torch==2.13.0+cpu \\
    {H} \\
    {H}
    # via
    #   -c (generated torch constraint, see compile_locks.py)
    #   -r services/inference/requirements/service.in
colorama==0.4.6 ; sys_platform == 'win32' \\
    {H}
uvicorn[standard]==0.52.1 \\
    {H}
"""


def test_parse_lock_counts_hashes_and_normalises_names():
    packages = compile_locks.parse_lock(GOOD.replace("numpy==", "Typing_Extensions=="))
    assert packages["typing-extensions"] == ("2.2.6", 1)
    assert packages["torch"] == ("2.13.0+cpu", 2)
    assert packages["colorama"] == ("0.4.6", 1)
    assert packages["uvicorn"] == ("0.52.1", 1)


def test_good_lock_verifies():
    assert compile_locks.verify_lock(GOOD, TARGET) == []


@pytest.mark.parametrize(
    "lock, expected",
    [
        (GOOD.replace("torch==2.13.0+cpu", "torch==2.13.0"), "torch must be 2.13.0+cpu, found 2.13.0"),
        (GOOD.replace("torch==2.13.0+cpu", "torch==2.13.0+cu130"), "torch must be 2.13.0+cpu"),
        (GOOD.replace("torch==", "notorch=="), "torch is missing"),
        (GOOD + f"nvidia-cublas-cu12==12.8.4.1 \\\n    {H}\n", "forbidden package in a core CPU lock: nvidia-cublas-cu12"),
        (GOOD + f"triton==3.5.0 \\\n    {H}\n", "forbidden package in a core CPU lock: triton"),
        (GOOD + f"cognee==0.3.0 \\\n    {H}\n", "forbidden package in a core CPU lock: cognee"),
        (GOOD + "rfc8785==0.1.4\n", "no --hash for rfc8785"),
        (GOOD.replace(f"--find-links {FIND_LINKS}\n", ""), f"lock does not record --find-links {FIND_LINKS}"),
        (
            GOOD.replace("--index-url", "--extra-index-url https://download.pytorch.org/whl/cpu\n--index-url"),
            "unexpected package source --extra-index-url https://download.pytorch.org/whl/cpu",
        ),
        (GOOD + "fastapi>=0.1\n", "not pinned with =="),
    ],
)
def test_bad_locks_are_reported(lock, expected):
    problems = compile_locks.verify_lock(lock, TARGET)
    assert any(expected in p for p in problems), problems


def test_uv_command_targets_linux_cpu_python_3_10_11_with_hashes():
    cmd = compile_locks.uv_command("uv", TARGET, Path("out.txt"), Path("c.txt"))
    assert cmd[:4] == ["uv", "pip", "compile", "services/inference/requirements/service.in"]
    joined = " ".join(cmd)
    assert "--python-version 3.10.11" in joined
    assert "--python-platform x86_64-manylinux_2_28" in joined
    assert "--generate-hashes" in cmd
    # PyPI is the only index; torch's CPU build comes from a torch-only find-links
    # page, so the PyTorch index's mirrors of other packages are never consulted.
    assert "--index-url https://pypi.org/simple" in joined
    assert f"--find-links {FIND_LINKS}" in joined
    assert "--extra-index-url" not in cmd
    assert "--constraint c.txt" in joined
    assert compile_locks.torch_constraint(TARGET) == "torch==2.13.0+cpu\n"


PAGE = (
    '<a href="https://download-r2.pytorch.org/whl/cpu/torch-2.13.0%2Bcpu-cp310-cp310-manylinux_2_28_x86_64.whl#sha256='
    + "1" * 64 + '">x</a>\n'
    '<a href="https://download-r2.pytorch.org/whl/cpu/torch-2.13.0%2Bcpu-cp310-cp310-manylinux_2_28_aarch64.whl#sha256='
    + "2" * 64 + '">x</a>\n'
    '<a href="https://download-r2.pytorch.org/whl/cpu/torch-2.13.0%2Bcpu-cp311-cp311-manylinux_2_28_x86_64.whl#sha256='
    + "3" * 64 + '">x</a>\n'
)


def test_torch_hash_is_taken_for_the_exact_wheel_only():
    assert compile_locks.torch_wheel_name(TARGET) == "torch-2.13.0+cpu-cp310-cp310-manylinux_2_28_x86_64.whl"
    assert compile_locks.torch_hash_from_page(PAGE, TARGET) == "1" * 64


@pytest.mark.parametrize("page", ["", PAGE.replace("1" * 64, "4" * 64) + PAGE])
def test_torch_hash_requires_exactly_one_match(page):
    with pytest.raises(RuntimeError, match="expected one sha256"):
        compile_locks.torch_hash_from_page(page, TARGET)


def test_add_torch_hash_makes_an_unhashed_lock_verify():
    unhashed = GOOD.replace(f"torch==2.13.0+cpu \\\n    {H} \\\n    {H}\n", "torch==2.13.0+cpu\n")
    assert "no --hash for torch" in compile_locks.verify_lock(unhashed, TARGET)
    fixed = compile_locks.add_torch_hash(unhashed, "f" * 64)
    assert f"torch==2.13.0+cpu \\\n    --hash=sha256:{'f' * 64}\n    # via" in fixed
    assert compile_locks.verify_lock(fixed, TARGET) == []
    assert compile_locks.add_torch_hash(GOOD, "f" * 64) == GOOD  # already hashed: unchanged


def test_service_in_is_the_input_and_pins_torch():
    text = compile_locks.SERVICE_IN.read_text(encoding="utf-8")
    assert f"torch=={compile_locks.TORCH_VERSION}" in text
    assert "cognee" not in [line.split("==")[0].strip() for line in text.splitlines()]


def test_committed_linux_lock_verifies():
    text = TARGET.output.read_text(encoding="utf-8")
    assert compile_locks.verify_lock(text, TARGET) == []
    assert "\r\n" not in text
