"""Tests for infra/scripts/compile_locks.py. uv is never executed: subprocess is stubbed."""
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))

import compile_locks as cl  # noqa: E402


@pytest.fixture
def root(tmp_path):
    req = tmp_path / cl.REQ_DIR
    req.mkdir(parents=True)
    (req / cl.INPUT_NAME).write_text("fastapi==0.141.1\n", encoding="utf-8")
    return tmp_path


def fake_uv(monkeypatch, rc=0):
    def run(cmd, cwd, capture_output, text):
        if rc == 0:
            Path(cmd[cmd.index("--output-file") + 1]).write_text(
                "fastapi==0.141.1 \\\n    --hash=sha256:aa\n", encoding="utf-8"
            )
        return subprocess.CompletedProcess(cmd, rc, "", "boom" if rc else "")

    monkeypatch.setattr(cl.subprocess, "run", run)
    monkeypatch.setattr(cl.shutil, "which", lambda _: "/usr/bin/uv")


def lock(root, name="linux-x86_64-cpu"):
    return root / cl.REQ_DIR / f"{name}.txt"


def test_missing_input_stops_without_generating(tmp_path):
    with pytest.raises(SystemExit) as e:
        cl.main(["--root", str(tmp_path), "--dry-run"])
    assert "service.in" in str(e.value)
    assert not (tmp_path / cl.REQ_DIR).exists()


def test_missing_uv_is_reported(root, monkeypatch):
    monkeypatch.setattr(cl.shutil, "which", lambda _: None)
    with pytest.raises(SystemExit) as e:
        cl.main(["--root", str(root)])
    assert "uv" in str(e.value)


def test_dry_run_prints_commands_and_writes_nothing(root, capsys):
    assert cl.main(["--root", str(root), "--dry-run"]) == 0
    lines = capsys.readouterr().out.splitlines()
    assert len(lines) == 3
    for line in lines:
        assert "--generate-hashes" in line and "--extra-index-url" in line and "--index-url" not in line.replace("--extra-index-url", "")
    assert sum("/whl/cu130" in l for l in lines) == 1
    assert sum("/whl/cpu" in l for l in lines) == 2
    assert not list((root / cl.REQ_DIR).glob("*.txt"))


def test_platform_and_python_version_flags():
    cmd = cl.build_command("linux-x86_64-cpu", Path("x.txt"))
    assert cmd[cmd.index("--python-version") + 1] == "3.10.11"
    assert cmd[cmd.index("--python-platform") + 1] == "x86_64-manylinux_2_28"


def test_write_mode_adds_header_and_lf_only(root, monkeypatch):
    fake_uv(monkeypatch)
    assert cl.main(["--root", str(root), "--platform", "linux-x86_64-cpu"]) == 0
    data = lock(root).read_bytes()
    assert data.startswith(b"# Generated by infra/scripts/compile_locks.py")
    assert b"\r\n" not in data
    assert not lock(root, "windows-x86_64-cpu").exists()


def test_check_passes_when_in_sync(root, monkeypatch):
    fake_uv(monkeypatch)
    cl.main(["--root", str(root)])
    assert cl.main(["--root", str(root), "--check"]) == 0


def test_check_tolerates_crlf_checkout(root, monkeypatch):
    fake_uv(monkeypatch)
    cl.main(["--root", str(root)])
    p = lock(root)
    p.write_bytes(p.read_bytes().replace(b"\n", b"\r\n"))
    assert cl.main(["--root", str(root), "--check"]) == 0


def test_check_detects_drift_and_missing(root, monkeypatch, capsys):
    fake_uv(monkeypatch)
    cl.main(["--root", str(root)])
    lock(root).write_text("stale\n", encoding="utf-8")
    lock(root, "windows-x86_64-cpu").unlink()
    assert cl.main(["--root", str(root), "--check"]) == 1
    out = capsys.readouterr().out
    assert "DRIFT linux-x86_64-cpu" in out and "DRIFT windows-x86_64-cpu" in out


def test_check_never_modifies_committed_locks(root, monkeypatch):
    fake_uv(monkeypatch)
    lock(root).parent.mkdir(parents=True, exist_ok=True)
    lock(root).write_text("stale\n", encoding="utf-8")
    cl.main(["--root", str(root), "--check", "--platform", "linux-x86_64-cpu"])
    assert lock(root).read_text(encoding="utf-8") == "stale\n"


def test_uv_failure_returns_1(root, monkeypatch, capsys):
    fake_uv(monkeypatch, rc=2)
    assert cl.main(["--root", str(root)]) == 1
    assert "boom" in capsys.readouterr().err
