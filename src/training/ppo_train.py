"""Stage 1D - PPO training loop.

Trains PPOActorCritic end-to-end (gradients flow through the CNN) on the
regime-stratified train-split transactions generated by
transaction_generator.py. One transaction = one episode (single-step),
per the approved liquidity-persistence decision. Validation-split
transactions are used for periodic evaluation/model-selection only - no
gradient updates.
"""
import numpy as np
import pandas as pd
import torch
import torch.optim as optim

from ..envs.cbdc_env import CBDCLiquidityEnv
from ..envs.stage1d_raw_obs_wrapper import Stage1DRawObservationWrapper, RAW_OBS_DIM
from ..models.stage1c_windowing import MAX_SLOTS
from ..models.ppo_actor_critic import PPOActorCritic

PPO_CLIP_EPS = 0.2
PPO_EPOCHS_PER_UPDATE = 4
GAMMA = 0.0  # single-step episodes (Decision 3) - no discounted future return within an episode
ENTROPY_COEF = 0.005  # was 0.0 (disabled). Evidence: deterministic actions over-concentrated on
# Bridge 0 despite the stochastic Dirichlet policy containing higher-reward capacity-aware actions -
# a small entropy bonus counteracts premature concentration without destabilizing training. This
# value is deliberately small: net.evaluate_actions()'s entropy can still be large-magnitude near
# mask boundaries in edge cases (see ppo_actor_critic.py's docstring on the 1-feasible-slot and
# 0-feasible-slot cases, where entropy is defined as exactly 0.0, not degenerate) - 0.005 was chosen
# as a conventional small-but-nonzero PPO entropy coefficient, not tuned/swept for this environment.


def _make_env_for_transactions(transactions_csv, structured_dir="data/structured", raw_dir="data/raw"):
    """Builds a CBDCLiquidityEnv whose requests_df is swapped for the
    generated transaction set (train/val/test), then wraps it with the
    raw observation pathway. Does not touch the real
    data/structured/transaction_requests.csv fixture file at all."""
    env = CBDCLiquidityEnv(structured_dir=structured_dir, raw_dir=raw_dir)
    tx_df = pd.read_csv(transactions_csv)
    env.requests_df = tx_df[["transaction_id", "sender_country", "receiver_country", "amount_usd", "simulation_date"]].reset_index(drop=True)
    env.max_steps = len(env.requests_df)
    return Stage1DRawObservationWrapper(env)


def collect_episode(wrapped_env, net, step_idx, device):
    """Single-transaction episode: reset forces step 0, so we manually
    position the underlying env at step_idx before observing (each
    'episode' here is exactly one transaction, iterated over the dataset
    rather than truly reset() each time - equivalent behavior, avoids
    rebuilding the env per transaction)."""
    base_env = wrapped_env.env.unwrapped
    base_env.current_step = step_idx
    req = base_env._current_request()
    mask, bridges, _ = base_env.get_feasibility_mask(req)

    obs = wrapped_env._wrap_obs(base_env._get_observation(req))
    raw_features = torch.tensor(obs["raw_features"], dtype=torch.float32, device=device).unsqueeze(0)
    windows = torch.tensor(obs["windows"], dtype=torch.float32, device=device).unsqueeze(0)
    mask_t = torch.tensor(mask, dtype=torch.bool, device=device).unsqueeze(0)

    with torch.no_grad():
        action, log_prob, value = net.act(raw_features, windows, mask_t)

    action_np = action.squeeze(0).cpu().numpy()
    base_env.current_step = step_idx  # step() reads current_step internally
    _, reward, _, _, info = base_env.step(action_np)

    return {
        "raw_features": raw_features.squeeze(0), "windows": windows.squeeze(0), "mask": mask_t.squeeze(0),
        "action": action.squeeze(0), "log_prob": log_prob.squeeze(0), "value": value.squeeze(0),
        "reward": float(reward), "info": info,
    }


def ppo_update(net, optimizer, batch, device):
    raw_features = torch.stack([b["raw_features"] for b in batch])
    windows = torch.stack([b["windows"] for b in batch])
    mask = torch.stack([b["mask"] for b in batch])
    actions = torch.stack([b["action"] for b in batch])
    old_log_probs = torch.stack([b["log_prob"] for b in batch]).detach()
    old_values = torch.stack([b["value"] for b in batch]).detach()
    rewards = torch.tensor([b["reward"] for b in batch], dtype=torch.float32, device=device)

    # Single-step episodes: return = reward, advantage = return - old_value.
    returns = rewards
    advantages = returns - old_values
    if advantages.numel() > 1 and advantages.std() > 1e-6:
        advantages = (advantages - advantages.mean()) / (advantages.std() + 1e-8)

    losses = []
    for _ in range(PPO_EPOCHS_PER_UPDATE):
        new_log_probs, new_values, entropy = net.evaluate_actions(raw_features, windows, mask, actions)
        ratio = torch.exp((new_log_probs - old_log_probs).clamp(-20, 20))
        surr1 = ratio * advantages
        surr2 = torch.clamp(ratio, 1 - PPO_CLIP_EPS, 1 + PPO_CLIP_EPS) * advantages
        policy_loss = -torch.min(surr1, surr2).mean()
        value_loss = torch.nn.functional.mse_loss(new_values, returns)
        entropy_bonus = entropy.mean()
        loss = policy_loss + 0.5 * value_loss - ENTROPY_COEF * entropy_bonus

        optimizer.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), max_norm=1.0)
        optimizer.step()
        losses.append(float(loss.item()))

    return {"policy_loss": float(policy_loss.item()), "value_loss": float(value_loss.item()), "mean_reward": float(rewards.mean().item())}


def train(train_csv, val_csv, n_epochs=5, batch_size=32, lr=3e-4, device="cpu", seed=42):
    torch.manual_seed(seed)
    np.random.seed(seed)

    device = torch.device(device)
    net = PPOActorCritic().to(device)
    optimizer = optim.Adam(net.parameters(), lr=lr)

    train_env = _make_env_for_transactions(train_csv)
    val_env = _make_env_for_transactions(val_csv)
    n_train = train_env.env.unwrapped.max_steps

    history = []
    best_val_reward = -np.inf
    best_state = None

    for epoch in range(n_epochs):
        order = np.random.permutation(n_train)
        epoch_rewards = []
        for start in range(0, n_train, batch_size):
            idxs = order[start:start + batch_size]
            batch = [collect_episode(train_env, net, int(i), device) for i in idxs]
            stats = ppo_update(net, optimizer, batch, device)
            epoch_rewards.extend([b["reward"] for b in batch])

        val_reward = evaluate_policy(val_env, net, device)
        history.append({
            "epoch": epoch, "train_mean_reward": float(np.mean(epoch_rewards)),
            "val_mean_reward": val_reward,
        })
        if val_reward > best_val_reward:
            best_val_reward = val_reward
            best_state = {k: v.clone() for k, v in net.state_dict().items()}

    if best_state is not None:
        net.load_state_dict(best_state)

    return net, history


def evaluate_policy(wrapped_env, net, device, deterministic=True):
    base_env = wrapped_env.env.unwrapped
    n = base_env.max_steps
    rewards = []
    with torch.no_grad():
        for i in range(n):
            base_env.current_step = i
            req = base_env._current_request()
            mask, bridges, _ = base_env.get_feasibility_mask(req)
            obs = wrapped_env._wrap_obs(base_env._get_observation(req))
            raw_features = torch.tensor(obs["raw_features"], dtype=torch.float32, device=device).unsqueeze(0)
            windows = torch.tensor(obs["windows"], dtype=torch.float32, device=device).unsqueeze(0)
            mask_t = torch.tensor(mask, dtype=torch.bool, device=device).unsqueeze(0)

            action, _, _ = net.act(raw_features, windows, mask_t, deterministic=deterministic)
            base_env.current_step = i
            _, reward, _, _, info = base_env.step(action.squeeze(0).cpu().numpy())
            rewards.append(reward)
    return float(np.mean(rewards))